CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    department VARCHAR(100),
    password_hash VARCHAR(255) NOT NULL,
    roles JSON NOT NULL DEFAULT '[]'::json,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX ix_users_email ON users (email);
CREATE TABLE resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_type VARCHAR(80) NOT NULL,
    owner_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    payload JSON NOT NULL DEFAULT '{}'::json,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_resources_type ON resources (resource_type);
CREATE INDEX ix_resources_owner ON resources (owner_id);

CREATE TABLE bank_imports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_key VARCHAR(64) NOT NULL UNIQUE,
    provider_transaction_id VARCHAR(255),
    transaction_at TIMESTAMPTZ NOT NULL,
    counterparty VARCHAR(255) NOT NULL DEFAULT '',
    amount BIGINT NOT NULL,
    direction VARCHAR(20) NOT NULL,
    balance_after BIGINT,
    matched_project VARCHAR(255),
    matched_contract_id BIGINT,
    status VARCHAR(30) NOT NULL,
    confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    source VARCHAR(80) NOT NULL DEFAULT '',
    committed_by BIGINT REFERENCES users(id),
    committed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_bank_imports_transaction_at ON bank_imports (transaction_at);
CREATE INDEX ix_bank_imports_status ON bank_imports (status);

CREATE TABLE bank_sync_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    fetched_count INTEGER NOT NULL DEFAULT 0,
    imported_count INTEGER NOT NULL DEFAULT 0,
    error_message VARCHAR(500),
    triggered_by BIGINT REFERENCES users(id)
);
CREATE INDEX ix_bank_sync_runs_status ON bank_sync_runs (status);
